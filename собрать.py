def карта(нид):
    к = нид // 100
    if к not in КЭШ_КАРТ:
        п = f'{ИСНАД}/site/data/n/{к}.json'
        КЭШ_КАРТ[к] = json.load(open(п, encoding='utf-8')) if os.path.exists(п) else {}
