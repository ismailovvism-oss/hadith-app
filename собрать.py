def карточки(нужные, хадисы_людей, имена):
    части, список = collections.defaultdict(dict), []
    for нид in sorted(нужные):
        ч = карта(нид)
        if not ч:
            continue
        ар = ч['abb'] or ч['name']
        ру = имена.get(str(нид), '')
        связи = lambda поле: [[и if и in нужные else 0, имена.get(str(и), ''), а, с] for и, с, а in ч[поле][:24]]
        части[нид // 100][нид] = {'id': нид, 'ru': ру, 'ar': ар, 'full': ч['name'], 'kunya': ч['kunya'], 'death': ч['death'],
            'tab': СТУПЕНИ.get(ч['tabaqa'], ''), 'g': ОЦЕНКИ.get(ч['grade'], ч['grade']), 'lv': ч['level'], 'ih': ч['ibn_hajar'],
            'dh': (ч['dhahabi'] or '')[:400], 'total': ч['hadiths'],
            'crit': [[к['who'], к['texts'][0][:320]] for к in ч['criticism'][:10] if к.get('texts')],
            'src': [[ц['book'], ц.get('vol'), ц.get('page')] for ц in ч['quotes'][:6]],
            'te': связи('teachers'), 'st': связи('students'),
            'books': [[б[0], ИМЕНА_КНИГ.get(б[0], б[1]), б[2]] for б in ч['books'][:14] if б[2]],
            'h': хадисы_людей.get(нид, {})}
        список.append([нид, ру, ар, ч['level']])
    if os.path.isdir(f'{ВЫХОД}/r'):
        shutil.rmtree(f'{ВЫХОД}/r')
    for к, з in части.items():
        писать(f'r/{к}.json', з)
    писать('narrators.json', список)


def имена_книги(люди, имена):
    "Для чипов иснада: {номер: [русское, арабское, уровень]}, без лишних обращений за карточкой."
