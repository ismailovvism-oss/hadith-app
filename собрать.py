def инлайн(т):
    т = html.escape(т, quote=False).replace('ﷺ', '<span class="saw">ﷺ</span>')
    т = re.sub(r'\[\^(\w+)\]', r'<sup>\1</sup>', т)
    т = re.sub(r'==(.+?)==', r'<mark>\1</mark>', т)
    т = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', т)
    return re.sub(r'\*(.+?)\*', r'<em>\1</em>', т)


def арабский(т, люди):
    """Размеченный текст hadith.dev → (вступление, иснад, матн, хвост); передатчики и аяты становятся ссылками."""
    т = re.sub(r'<رقم_الفقرة[^>]*/>|<الصفحات[^>]*/>|<نه/>', '', т)
    т = re.sub(r'<رقم_حديث[^>]*>.*?</رقم_حديث>', '', т, flags=re.S).replace('&quot;', '"').replace('&amp;', '&')
    т = re.sub(r'<(سند_مخفي|متن_مخفي)[^>]*>.*?</\1>|<[^<>]*\sنص="[^"]*"[^<>]*/>', '', т, flags=re.S)

    def рави(м):
        нид, текст = м.group(1), re.sub(r'<[^>]+>', '', м.group(2)).strip()
        хвост = ''
        if текст.endswith('،'):
            текст, хвост = текст[:-1].rstrip(), ' ،'
        люди.add(int(нид))
        return f'<a class="r" data-id="{нид}">{текст}</a>{хвост} '

    def аят(м):
        с, а = re.search(r'رقم_السورة="(\d+)"', м.group(1)), re.search(r'الآية="(\d+)', м.group(1))
        текст = re.sub(r'<[^>]+>', '', м.group(2)).strip()
        return f'<span class="ay" data-ay="{с.group(1)}:{а.group(1)}">{текст}</span> ' if с and а else текст + ' '

    т = re.sub(r'<راوي[^>]*?ربط="(\d+)[^"]*"[^>]*>(.*?)</راوي>', рави, т, flags=re.S)
    т = re.sub(r'<آية([^>]*)>(.*?)</آية>', аят, т, flags=re.S)
    т = re.sub(r'<متن(?=[\s>])', '\x01<متن', т).replace('</متن>', '\x02')
    т = re.sub(r'<حديث[^>]*>', '\x03', т)
    т = re.sub(r'</?(?!a\b|/a\b|span\b|/span\b)[^\x00-\x7f][^>]*>', '', т)
    чисто = lambda с: re.sub(r'\s+', ' ', re.sub('[\x01\x02\x03]', '', с)).strip(' -.')
    вст, есть, тело = т.partition('\x03')
    if not есть:
        return чисто(вст), '', '', ''
    иснад, _, ост = тело.partition('\x01')
    матн, _, хвост = ост.rpartition('\x02') if '\x02' in ост else (ост, '', '')
    return чисто(вст), чисто(иснад), чисто(матн), чисто(хвост)


def перевод_книги(путь):
    главы, г, х, вопросы = [], None, None, None
    for строка in open(путь, encoding='utf-8'):
        с = строка.strip()
        if с.startswith('## Вопросы'):
            вопросы = []
            continue
        if вопросы is not None:
            if м := re.match(r'\d+\.\s+(.+)', с):
                вопросы.append(м.group(1))
            continue
        if not с or с.startswith('# '):
            continue
        if с.startswith('## '):
            г = {'t': re.sub(r'^Глава:?\s*', '', с[3:]), 'src': с, 'intro': [], 'intro_src': [], 'fn': [], 'fn_src': [], 'h': []}
            главы.append(г)
            х = None
        elif с.startswith('### '):
            н, _, загл = с[4:].partition('|')
            х = {'n': н.strip(), 't': загл.strip(), 'ru': [], 'ru_src': [], 'fn': [], 'fn_src': []}
            г['h'].append(х)
        elif м := re.match(r'\[\^(\w+)\]:\s*(.+)', с):
            (х or г)['fn'].append(f'<sup>{м.group(1)}</sup> {инлайн(м.group(2))}')
            (х or г)['fn_src'].append(с)
        elif г is not None:
            (х['ru'] if х else г['intro']).append(инлайн(с))
            (х['ru_src'] if х else г['intro_src']).append(с)
    for г in главы:  # сноски нумеруются внутри хадиса, а не сквозь книгу
        for х in г['h']:
            новые = {}
            чин = lambda м: f'<sup>{новые.setdefault(м.group(1), len(новые) + 1)}</sup>'
            х['ru'] = [re.sub(r'<sup>(\w+)</sup>', чин, п) for п in х['ru']]
            х['fn'] = [re.sub(r'<sup>(\w+)</sup>', чин, п) for п in х['fn']]
    return главы, вопросы or []


def статьи_шарха():
    """Ясный шарх: один файл на статью в data/sharh, в выдаче список готовых ключей."""
    готово = {}
    исходник = open(f'{ЗДЕСЬ}/ясный-шарх/пилот/пилот-1.md', encoding='utf-8').read()
    блоки = re.split(r'\n---\n', исходник)
    блоки += [open(ф, encoding='utf-8').read() for ф in sorted(glob.glob(f'{ЗДЕСЬ}/ясный-шарх/статьи/*.md'))]
    for блок in блоки:
        if not блок.strip().startswith('## '):
            continue
        шапка, *строки = блок.strip().split('\n')
        ключ, заглавие = [с.strip() for с in шапка[3:].split('|')]
        тело, диалог, вывод, где, передатчик, перевод = [], [], None, '', '', ''

        def сброс():
            if диалог:
                тело.append('<p class="dlg">' + '<br>'.join(диалог) + '</p>')
                диалог.clear()

        for с in map(str.strip, строки):
            if not с:
                сброс()
            elif с.startswith('Перевод: '):
                перевод = с[9:]
            elif с.startswith(('Где: ', 'Оценка: ')):
                где += f'<p class="where">{инлайн(с.split(": ", 1)[1])}</p>'
            elif с.startswith('Передатчик: '):
                передатчик = инлайн(с[12:])
            elif с == 'Что взять:':
                сброс()
                вывод = []
            elif с.startswith('- ') and вывод is not None:
                вывод.append(инлайн(с[2:]))
            elif с.startswith('— '):
                диалог.append(инлайн(с))
            elif с.startswith('### '):
                сброс()
                тело.append(f'<h5>{инлайн(с[4:])}</h5>')
            elif с.startswith('Рассказ: '):
                сброс()
                текст, пометка = с[9:].split(' | ')
                тело.append(f'<aside class="story"><p>{инлайн(текст)}</p><p class="flag">{инлайн(пометка)}</p></aside>')
            else:
                сброс()
                тело.append(f'<p>{инлайн(с)}</p>')
        сброс()
        итог = где + ''.join(тело)
        if вывод:
            итог += '<section class="take"><h4>Что взять</h4><ul>' + ''.join(f'<li>{п}</li>' for п in вывод) + '</ul></section>'
        if передатчик:
            итог += f'<p class="narr"><strong>Передатчик.</strong> {передатчик}</p>'
        писать(f'sharh/{ключ}.json', {'t': заглавие.strip('«»'), 'html': итог})
        готово[ключ] = {'t': заглавие, 'перевод': инлайн(перевод)}
    return готово


def норм_ар(т):
    т = re.sub('[ً-ْٰـ]', '', т)
    т = re.sub('[أإآٱ]', 'ا', т).replace('ى', 'ي').replace('ة', 'ه').replace('ؤ', 'و').replace('ئ', 'ي')
    return re.sub(r'\s+', ' ', re.sub(r'[^ء-ي\s]', ' ', т)).strip()


