"""Проверка статей Ясного шарха, запускается после письма и после каждой правки.

    python3 ясный-шарх/проверить.py          # все статьи из ясный-шарх/статьи
    python3 ясный-шарх/проверить.py 8-12 40  # только эти хадисы

Смотрит: устройство статьи, строку «Где», слова из хадиса (==…==) против перевода, запретные слова и опоры:
каждая цитата из ясный-шарх/опоры/<ключ>.txt должна стоять на указанной странице источника.
Формат опоры: «Фатх 1/56 | арабская цитата | что подтверждает». Книга вне списка: «Шамиля <book_id>/<page_id>».
Ошибка — выход с кодом 1. Смысл не проверяется: совпадение цитаты не значит, что она верно понята.
"""
import glob, json, os, re, sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КОРЕНЬ = os.path.join(ЗДЕСЬ, '..')
КНИГИ = {'Фатх': 1673, 'Умда': 5756, 'Раджаб': 137, 'Джами': 949, 'Миркат': 8176}
ЗАПРЕТ = ['удовлетворил', 'насытил', 'утолил', 'важно отметить', 'стоит отметить', 'следует отметить', 'таким образом,',
          'в заключение', 'подводя итог', 'не просто ', 'глубокий смысл', 'ключевую роль']
МИН_СЛОВ = 400
МИН_СЛОВ_ПОВТОРА = 120  # другая передача уже разобранного хадиса
ПОВТОРЫ = {21, 28, 51, 54, 62, 72, 78, 87, 95, 96, 102, 105, 124, 129, 131, 261, 262, 263, 272}


def норм(т):
    т = re.sub('[ً-ْٰـ]', '', т)
    т = re.sub('[أإآٱ]', 'ا', т).replace('ى', 'ي').replace('ة', 'ه').replace('ؤ', 'و').replace('ئ', 'ي')
    return re.sub(r'\s+', ' ', re.sub(r'[^ء-ي\s]', ' ', т)).strip()


def рус(т):
    return re.sub(r'\s+', ' ', re.sub(r'[^а-яё\s]', ' ', т.lower().replace('ё', 'е'))).strip()


def источники():
    итог = {}
    for имя, б in КНИГИ.items():
        стр = {}
        for с in open(f'{КОРЕНЬ}/данные/источники/{б}.jsonl', encoding='utf-8'):
            п = json.loads(с)
            стр.setdefault(f'{п["v"] or 1}/{п["p"]}', []).append(п)  # у однотомников тома нет
            стр.setdefault(f'id{п["id"]}', []).append(п)
        итог[имя] = стр
    return итог


заглавия = {}


def переводы():
    итог = {}
    for ф in sorted(glob.glob(f'{КОРЕНЬ}/data/bukhari/[0-9][0-9].json')):
        for гл in json.load(open(ф, encoding='utf-8'))['ch']:
            for х in гл['h']:
                итог[х['n']] = ' '.join(х.get('ru', []))
                заглавия[х['n']] = х.get('t', '')
    return итог


def на_странице(текст_цитаты, страницы):
    ц = норм(текст_цитаты)
    for п in страницы:
        if ц in норм(п['t'] + ' ' + п['f']):
            return True
    return False


def проверить(путь, ист, пер):
    ошибки, замечания = [], []
    текст = open(путь, encoding='utf-8').read()
    ключ = os.path.basename(путь)[:-3]
    номер = ключ.split('-')[1]
    if not текст.startswith(f'## {ключ} | '):
        ошибки.append('первая строка не вида «## ключ | заглавие»')
    if 'Где: ' not in текст:
        ошибки.append('нет строки «Где:»')
    if 'Перевод:' in текст:
        ошибки.append('строка «Перевод:» не нужна, перевод берётся из перевод/бухари')
    пункты = re.findall(r'^- .+', текст.split('Что взять:')[-1], re.M) if 'Что взять:' in текст else []
    if not 3 <= len(пункты) <= 5:
        ошибки.append(f'в «Что взять» пунктов {len(пункты)}, нужно 3–4')
    разбор = текст.split('Что взять:')[0].split('\n', 3)[-1]
    слов = len(re.findall(r'[а-яёА-ЯЁ]+', разбор))
    повтор = (int(re.sub(r'\D', '', номер)) in ПОВТОРЫ or номер.endswith('б')
              or any(п in заглавия.get(номер, '') for п in ('другая передача', 'другой путь')))
    порог = МИН_СЛОВ_ПОВТОРА if повтор else МИН_СЛОВ
    if слов < порог:
        ошибки.append(f'разбор {слов} слов, нужно не меньше {порог}')
    if re.search(r'[؀-ۿ]', текст):
        ошибки.append('арабская графика в тексте статьи')
    низ = текст.lower()
    for с in ЗАПРЕТ:
        if с in низ:
            ошибки.append(f'запретное слово: «{с}»')
    перевод = рус(re.sub(r'<[^>]+>', '', пер.get(номер, '')))
    for м in re.findall(r'==«?([^=»]+?)»?==', текст):
        м2 = рус(м)
        if м2 and м2 not in перевод:
            замечания.append(f'выделенные слова не из перевода: «{м}»')
    if not re.findall(r'==', текст):
        ошибки.append('нет ни одного слова хадиса, выделенного ==«…»==')
    файл = f'{КОРЕНЬ}/ясный-шарх/опоры/{ключ}.txt'
    if not os.path.exists(файл):
        ошибки.append('нет файла опор')
        return ошибки, замечания, 0
    строк = 0
    for ск in open(файл, encoding='utf-8'):
        if not ск.strip():
            continue
        части = [ч.strip() for ч in ск.split('|')]
        if len(части) != 3:
            ошибки.append(f'опора не из трёх частей: {ск[:60]}')
            continue
        адрес, цитата, _ = части
        строк += 1
        if len(норм(цитата).split()) < 3:
            ошибки.append(f'опора короче трёх слов: {адрес}')
        адрес = адрес.replace('None/', '1/')
        ш = re.fullmatch(r'Шамиля (\d+)/(\d+)', адрес)
        свои = {б: и for и, б in КНИГИ.items()}
        if ш and int(ш.group(1)) in свои:
            адрес = f'{свои[int(ш.group(1))]} id{ш.group(2)}'
        м = re.fullmatch(r'(\S+) (\d+/\d+|id\d+)', адрес)
        if м and м.group(1) == 'Шамиля':
            замечания.append(f'внешняя опора, сверить вручную: {адрес}')
        elif not м or м.group(1) not in ист:
            ошибки.append(f'неизвестный адрес опоры: {адрес}')
        elif м.group(2) not in ист[м.group(1)]:
            ошибки.append(f'нет такой страницы: {адрес}')
        elif not на_странице(цитата, ист[м.group(1)][м.group(2)]):
            ошибки.append(f'цитаты нет на странице {адрес}: {цитата[:70]}')
    скобок = len(re.findall(r'\((?:[^()]*(?:Ибн|аль-|ан-|ас-|ат-|Али|Муслим|Ахмад|Малик)[^()]*)\)', разбор))
    if строк < max(скобок // 2, 4):
        замечания.append(f'опор мало: {строк} на {скобок} ссылок в скобках')
    return ошибки, замечания, строк


нужно = set()
for а in sys.argv[1:]:
    if а.endswith('б'):
        нужно.add(а)
        continue
    от, _, до = а.partition('-')
    нужно.update(к for н in range(int(от), int(до or от) + 1) for к in (str(н), f'{н}б'))  # «855б» — запись None с текстом
ист, пер = источники(), переводы()
плохих = всего = 0
for путь in sorted(glob.glob(f'{КОРЕНЬ}/ясный-шарх/статьи/*.md'), key=lambda п: (int(re.sub(r'\D', '', os.path.basename(п))), п)):
    номер = os.path.basename(путь)[:-3].split('-')[1]
    if нужно and номер not in нужно:
        continue
    всего += 1
    ош, зам, строк = проверить(путь, ист, пер)
    плохих += bool(ош)
    if ош or зам:
        print(f'{номер}: опор {строк}')
        for с in ош:
            print('   ошибка:', с)
        for с in зам:
            print('   замечание:', с)
print(f'статей {всего}, с ошибками {плохих}')
sys.exit(1 if плохих else 0)
