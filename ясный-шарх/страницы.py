"""Дочитать страницы источника, которых нет в досье: python3 ясный-шарх/страницы.py Фатх 8 718 721
Книги: Фатх, Умда, Раджаб, Джами, Миркат. Адрес в опоре пишется так же: Фатх 8/718.
"""
import json, os, re, sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
КНИГИ = {'Фатх': 1673, 'Умда': 5756, 'Раджаб': 137, 'Джами': 949, 'Миркат': 8176}
имя, том, от, до = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])
for с in open(f'{ЗДЕСЬ}/../данные/источники/{КНИГИ[имя]}.jsonl', encoding='utf-8'):
    п = json.loads(с)
    if п['v'] == том and от <= п['p'] <= до:
        print(f'[{имя} {п["v"]}/{п["p"]}, id {п["id"]}]\n' + re.sub('[ً-ْٰـ]', '', п['t']) + '\n')
