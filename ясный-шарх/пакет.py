def собрать_перевод(кн, частей):
    """Части перевода из всех пакетов книги (поздний ответ на часть заменяет ранний) → перевод/бухари/NN.md."""
    ответы = {}
    for ф in sorted(glob.glob(f'{ПАКЕТЫ}/*/p{кн:02}-*.txt'), key=os.path.getmtime):
        ответы[int(ф[-6:-4])] = читать(ф)
    нет = [н for н in range(1, частей + 1) if н not in ответы]
    if нет:
        print('перевод не собран, нет частей:', *нет)
        return
    тексты, вопросы = [], []
    for н in range(1, частей + 1):
        м = re.search(r'=== ПЕРЕВОД ===\s*(.*?)\s*(?:=== ВОПРОСЫ ===\s*(.*))?$', ответы[н], re.S)
        if not м:
            print(f'часть {н}: ответ не по форме')
            return
        тексты.append(м.group(1).strip())
        вопросы += [с for с in (м.group(2) or '').splitlines() if с.strip().startswith('-') and not
                    re.match(r'-\s*\S+:\s*нет\.?$', с.strip())]
    названия = json.load(open(f'{КОРЕНЬ}/перевод/бухари/книги.json', encoding='utf-8'))
    итог = f'# {названия[кн - 1]}\n\n' + '\n\n'.join(тексты) + '\n\n## Вопросы\n\n' + '\n'.join(вопросы) + '\n'
    путь = f'{КОРЕНЬ}/перевод/бухари/{кн:02}.md'
    if os.path.exists(путь):
        путь = f'{ПАКЕТЫ}/перевод-{кн:02}.md'
    open(путь, 'w', encoding='utf-8').write(итог)
    print('перевод собран:', путь)


def разобрать_ответ(текст):
    м = re.search(r'=== СТАТЬЯ ===\s*(.*?)\s*=== ОПОРЫ ===\s*(.*?)\s*(?:=== ОТЧЁТ ===\s*(.*))?$', текст, re.S)
    return (м.group(1).strip(), м.group(2).strip(), (м.group(3) or '').strip()) if м else None


def забрать():
    к = клиент()
    сумма = {'input': 0, 'output': 0, 'cache_read': 0, 'cache_write': 0}
    for файл in sorted(glob.glob(f'{ПАКЕТЫ}/*.json')):
        мета = json.load(open(файл))
        if мета.get('забран'):
            continue
        пакет = к.messages.batches.retrieve(мета['id'])
        if пакет.processing_status != 'ended':
            print(мета['id'], пакет.processing_status, пакет.request_counts)
            continue
        папка = f'{ПАКЕТЫ}/{мета["id"]}'
        os.makedirs(папка, exist_ok=True)
        готово, сбой = [], []
        for р in к.messages.batches.results(мета['id']):
            ключ = р.custom_id[1:].replace('-b', 'б') if р.custom_id.startswith('h') else р.custom_id  # p10-01, jami-2
            имя = ключ if '-' in ключ else f'bukhari-{ключ}'
            if р.result.type != 'succeeded':
                сбой.append(f'{ключ}: {р.result.type}')
                continue
            сообщ = р.result.message
            у = сообщ.usage
            сумма['input'] += у.input_tokens
            сумма['output'] += у.output_tokens
            сумма['cache_read'] += у.cache_read_input_tokens or 0
            сумма['cache_write'] += у.cache_creation_input_tokens or 0
            текст = ''.join(б.text for б in сообщ.content if б.type == 'text')
            if мета['имя'] == 'перевод':
                if сообщ.stop_reason != 'end_turn' or '=== ПЕРЕВОД ===' not in текст:
                    сбой.append(f'{ключ}: ответ не по форме ({сообщ.stop_reason})')
                    continue
                open(f'{папка}/{ключ}.txt', 'w', encoding='utf-8').write(текст)
                готово.append(ключ)
                continue
            open(f'{папка}/{ключ}.txt', 'w', encoding='utf-8').write(текст)
            части = разобрать_ответ(текст)
            if not части or not части[0].startswith(f'## {имя} |'):
                сбой.append(f'{ключ}: ответ не по форме ({сообщ.stop_reason})')
                continue
            open(f'{ЗДЕСЬ}/статьи/{имя}.md', 'w', encoding='utf-8').write(части[0] + '\n')
            open(f'{ЗДЕСЬ}/опоры/{имя}.txt', 'w', encoding='utf-8').write(части[1] + '\n')
            if части[2]:
                open(f'{папка}/{ключ}.отчёт.txt', 'w', encoding='utf-8').write(части[2] + '\n')
            if сообщ.stop_reason != 'end_turn':
                сбой.append(f'{ключ}: записан, но ответ обрезан ({сообщ.stop_reason}), нужен «исправить»')
            готово.append(ключ)
        мета['забран'] = True
        json.dump(мета, open(файл, 'w'), ensure_ascii=False)
        print(f'пакет {мета["id"]}: записано {len(готово)}, сбоев {len(сбой)}')
        for с in сбой:
            print('  сбой', с)
        if мета['имя'] == 'перевод':
            собрать_перевод(мета['книга'], мета['частей'])
    цена = sum(сумма[к] * ЦЕНА[к] for к in сумма) / 1e6
    print('токены', сумма, f'≈ ${цена:.2f}')


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return
    к, ар = sys.argv[1], sys.argv[2:]
    проба = None
    if '--проба' in ар:
        i = ар.index('--проба')
        проба = int(ар[i + 1])
        ар = ар[:i] + ар[i + 2:]
    все = хадисы()
    if к == 'отправить':
        ключи = нужные(номера(ар), все)
        ждут = [к for к in ключи if ждёт_главной(к, все)]
        if ждут:
            print(f'ждут главных статей ({len(ждут)}), уйдут повторной отправкой после «забрать»:', *ждут)
        ключи = [к for к in ключи if к not in ждут]
        отправить(ключи[:проба] if проба else ключи, все)
    elif к == 'исправить':
        нн = номера(ар)
        ош = ошибки_проверки(нн)
        поправки = {}
        for ключ in [к for н in нн for к in (н, н + 'б')]:
            for ф in sorted(glob.glob(f'{ПАКЕТЫ}/*/{ключ}.txt'), key=os.path.getmtime)[-1:]:
                ответ, текст = читать(ф), ош.get(ключ, '')
                # на xhigh ответ бывает обрезан по длине прямо в опорах, иногда ровно по концу строки: проверка этого не видит
                if '=== ОТЧЁТ ===' not in ответ:
                    текст = ('Прежний ответ оборвался по длине на опорах, отчёта нет. Статью повтори без изменений, опоры '
                             'допиши ко всем утверждениям до конца статьи, отчёт обязателен.\n' + текст)
                if текст:
                    поправки[ключ] = {'ошибки': текст, 'ответ': ответ}
        if not поправки:
            print('исправлять нечего: либо ошибок нет, либо статьи писались не пакетом')
            return
        отправить(sorted(поправки), все, поправки, 'исправить')
    elif к == 'переписать':
        ключи = [к for к in номера(ар) if os.path.exists(f'{ЗДЕСЬ}/статьи/bukhari-{к}.md')]
        отправить(ключи, все, имя='переписать', прежние={к: читать(f'{ЗДЕСЬ}/статьи/bukhari-{к}.md') for к in ключи})
    elif к == 'основы':
        ключи = полка_основ(set(номера(ар)))
        отправить(ключи[:проба] if проба else ключи, все, имя='основы')
    elif к == 'перевести':
        отправить_перевод(int(ар[0]), [int(ч) for ч in ар[1:]] or None)
    elif к == 'статус':
        кл = клиент()
        for файл in sorted(glob.glob(f'{ПАКЕТЫ}/*.json')):
            мета = json.load(open(файл))
            п = кл.messages.batches.retrieve(мета['id'])
            print(мета['id'], мета['имя'], п.processing_status, п.request_counts, 'забран' if мета.get('забран') else '')
    elif к == 'забрать':
        забрать()
    else:
        print(__doc__)


if __name__ == '__main__':
    main()
