def полка_основ(номера_джами):
    """Ключи ненаписанных статей «Пятидесяти основ» по номерам в «Джами»: у аль-Бухари — его номер, иначе jami-N."""
    пилот = set(re.findall(r'^## (\S+) \|', читать(f'{ЗДЕСЬ}/пилот/пилот-1.md'), re.M))
    итог = []
    for с in open(f'{ЗДЕСЬ}/Джами-50.md', encoding='utf-8'):
        м = re.match(r'\| (\d+) \|[^|]+\| ([^|]+) \|', с)
        if not м or м.group(1) not in номера_джами or м.group(1) == '12':  # хадис 12 в пилоте: tirmidhi-2317
            continue
        б = re.fullmatch(r'Бухари (\d+)', м.group(2).strip())
        ключ = б.group(1) if б else f'jami-{м.group(1)}'
        имя = ключ if '-' in ключ else f'bukhari-{ключ}'
        if имя not in пилот and not os.path.exists(f'{ЗДЕСЬ}/статьи/{имя}.md'):
            итог.append(ключ)
    return итог


