def раздел(текст, начало, конец=None):
    """Кусок текста от строки, начинающейся с «начало», до следующего заголовка того же уровня."""
    i = текст.find(начало)
    if i < 0:
        return ''
    уровень = re.match(r'#+', начало).group(0)
    j = текст.find('\n' + уровень + ' ', i + len(начало))
    return текст[i:j if j > 0 else None]


