def отправить(ключи, все, поправки=None, имя='статьи', прежние=None):
    сис = система()
    запросы = [{'custom_id': к if '-' in к else 'h' + к.replace('б', '-b'), 'params': {
        'model': МОДЕЛЬ, 'max_tokens': 128000, 'output_config': {'effort': УСИЛИЕ}, 'system': сис,
        'messages': [{'role': 'user', 'content': сообщение(к, все, (поправки or {}).get(к), (прежние or {}).get(к))}]}}
        for к in ключи]
    пакет = клиент().messages.batches.create(requests=запросы)
    os.makedirs(ПАКЕТЫ, exist_ok=True)
    json.dump({'id': пакет.id, 'имя': имя, 'ключи': ключи}, open(f'{ПАКЕТЫ}/{пакет.id}.json', 'w'), ensure_ascii=False)
    print(f'отправлено {len(ключи)}: {" ".join(ключи)}\nпакет {пакет.id}, {пакет.processing_status}')


