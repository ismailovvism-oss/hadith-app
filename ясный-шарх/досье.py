НАЧАЛА_УМДЫ = {4: 63, 5: 68, 6: 72, 7: 76, 8: 117, 74: 385, 102: 459, 110: 477, 113: 492, 126: 526, 127: 528, 128: 529,
               129: 532, 130: 535, 131: 537, 132: 538, 133: 541, 134: 545, 135: 552, 291: 873,
               334: 946, 335: 950, 336: 954, 337: 957, 338: 960, 339: 963, 340: 965, 341: 965, 342: 965, 343: 966,
               344: 968, 345: 977, 346: 978, 347: 979, 348: 981, 349: 983}
ДЖАМИ_НОМЕРА = {1: 1, 8: 3, 13: 13, 25: 8, 34: 48, 50: 2, 52: 6}
ЦИФРЫ = str.maketrans('٠١٢٣٤٥٦٧٨٩', '0123456789')
ОТМЕТКА = re.compile(r'(?:^|\n)\s*([٠-٩]{1,4})\s*-\s*و?(?:حدثنا|حدثني|أخبرنا|أخبرني)')


def без_огласовок(т):
    return re.sub('[ً-ْٰـ]', '', т)


def норм(т):
    т = без_огласовок(т)
    т = re.sub('[أإآٱ]', 'ا', т).replace('ى', 'ي').replace('ة', 'ه').replace('ؤ', 'و').replace('ئ', 'ي')
    return re.sub(r'\s+', ' ', re.sub(r'[^ء-ي\s]', ' ', т)).strip()


def книга(б):
    return [json.loads(с) for с in open(f'{ИСТ}/{б}.jsonl', encoding='utf-8')]


class Книга:
    def __init__(я, б, начала=None):
        я.стр = книга(б)
        я.по_ид = {с['id']: и for и, с in enumerate(я.стр)}
        # Номер в поле стоит не на каждой странице, а хадис часто начат посреди страницы: отметка «٧٠٧ - حدثنا» в тексте
        # точнее. У аль-Айни с Книги азана поле пустое совсем. Каждый номер берём с первой страницы, где он встретился.
        кандидаты, было, позиции = [], set(), {}
        for и, с in enumerate(я.стр):
            if not с['t']:
                continue
            отметки = [(int(м.group(1).translate(ЦИФРЫ)), м.start()) for м in ОТМЕТКА.finditer(без_огласовок(с['t']))]
            for н, поз in отметки or ([(с['n'], None)] if с['n'] else []):
                if н <= 7600 and н not in было:
                    кандидаты.append((и, н))
                    было.add(н)
                    if поз is not None:
                        позиции[н] = (и, поз)
        # в базе бывают мусорные номера (5361, 75332): номер берём, если он продолжает предыдущий или его продолжает следующий
        я.номера, прежний = [], 0
        for к, (и, н) in enumerate(кандидаты):
            следующий = кандидаты[к + 1][1] if к + 1 < len(кандидаты) else None
            if прежний <= н <= прежний + 80 or (следующий is not None and н <= следующий <= н + 80):
                я.номера.append((н, и))
                прежний = н
        я.номера.sort()
        if начала:
            я.номера = sorted([(н, и) for н, и in я.номера if н not in начала] + [(н, я.по_ид[ид]) for н, ид in начала.items()])
        я.отметки = {н: позиции[н] for н, и in я.номера if позиции.get(н, (None,))[0] == и}

    def подряд(я, н):
        """Следующий хадис, если он приведён сразу за этим и между ними нет ни одного «قوله», то есть разбора. Иначе None."""
        дальше = [м for м, _ in я.номера if м > н]
        if н not in я.отметки or not дальше or дальше[0] not in я.отметки:
            return None
        (и1, п1), (и2, п2) = я.отметки[н], я.отметки[дальше[0]]
        if not 0 <= и2 - и1 <= 3:
            return None
        стр = [без_огласовок(я.стр[и]['t']) for и in range(и1, и2 + 1)]
        между = стр[0][п1:п2] if и1 == и2 else стр[0][п1:] + ''.join(стр[1:-1]) + стр[-1][:п2]
        return None if 'قوله' in между else дальше[0]

    def место(я, н):
        """Страницы хадиса: от страницы, где он начат, до страницы, где начат следующий, включая её."""
        до = [и for м, и in я.номера if м <= н]
        if not до:
            return None
        нач = max(до)
        после = [и for м, и in я.номера if м > н and и >= нач]  # ошибочный номер на странице раньше начала не в счёт
        return нач, min(после) if после else нач


def блок(имя, с, сноски=False):
    хвост = f'\nСноска издателя, не слова автора: {без_огласовок(с["f"])}\n' if сноски and с['f'] else ''
    return f'\n[{имя} {с["v"] or 1}/{с["p"]}, id {с["id"]}]\n{без_огласовок(с["t"])}\n{хвост}'


def срезать_умду(текст):
    """Аль-Айни разбит на рубрики «(بيان …)»: убираем грамматику, огласовку имён и тонкости цепи."""
    части = re.split(r'(\((?:بيان|ذكر)[^()]{2,40}\))', текст)
    итог, брать = [части[0]], True
    for и in range(1, len(части), 2):
        заглавие = части[и]
        брать = not any(сл in заглавие for сл in НЕ_БРАТЬ_У_АЙНИ)
        if брать:
            итог += [заглавие, части[и + 1]]
    return ''.join(итог)


def окна(ар, длина=5):
    сл = норм(ар).split()
    return [' '.join(сл[и:и + длина]) for и in range(max(len(сл) - длина + 1, 1))]


def найти_фразой(кн, ар, нужно=2, страниц=СТРАНИЦ_МИРКАТА, до=None):
    """Нумерация своя или её нет: место ищем по окнам текста хадиса."""
    вин = окна(ар)[:60]
    счёт = []
    for и, с in enumerate(кн.стр[:до]):
        т = с.setdefault('_н', норм(с['t']))
        ч = sum(1 for о in вин if о in т)
        if ч >= нужно:
            счёт.append((ч, и))
    if not счёт:
        return []
    и = max(счёт)[1]
    первый = min(п for ч, п in счёт if abs(п - и) <= 3)
    return кн.стр[первый:первый + страниц]


def дополнить_начала(кн, все):
    """Номера на странице нет или он испорчен: ищем начало хадиса по его тексту в 40 страницах после предыдущего.
    Шарх приводит хадис целиком в начале разбора, поэтому страница, где сошлось много окон текста, и есть начало."""
    есть = {м: и for м, и in кн.номера}
    пред = None
    for н in range(1, 7600):
        if str(н) not in все:
            continue
        if н in есть:
            пред = есть[н]
            continue
        if пред is None:
            continue
        в = окна(re.sub(r'<[^>]+>', '', все[str(н)][2]['x']), 4)
        if not в:
            continue
        for и in range(пред, min(пред + 40, len(кн.стр))):
            т = кн.стр[и].setdefault('_н', норм(кн.стр[и]['t']))
            if sum(1 for о in в if о in т) >= max(2, len(в) * 0.3):
                кн.номера.append((н, и))
                есть[н] = пред = и
                break
    кн.номера.sort()


def хадисы():
    итог = {}
    for ф in range(1, 98):
        ф = f'{ф:02}'
        путь = f'{КОРЕНЬ}/data/bukhari/{ф}.json'
        if not os.path.exists(путь):
            continue
        д = json.load(open(путь, encoding='utf-8'))
        дт = json.load(open(f'{КОРЕНЬ}/data/bukhari/{ф}.t.json', encoding='utf-8'))
        for гл in д['ch']:
            for х in гл['h']:
                итог[х['n']] = (д, гл, х, дт.get(х['n'], {}))
    return итог


def повторы(фатх, н):
    """Строка «[الحديث ٧ - أطرافه في: …]» стоит у первого места хадиса; бывают опечатки, пустые места отсекаются сами."""
    нач, кон = фатх.место(н)
    for с in фатх.стр[нач:кон + 1]:
        м = re.search(rf'\[الحديث\s+{str(н).translate(str.maketrans("0123456789", "٠١٢٣٤٥٦٧٨٩"))}\s*-\s*(?:أطرافه|طرفاه|طرفه)[^\]]*\]', без_огласовок(с['t']))
        if м:
            return sorted(int(ч.translate(ЦИФРЫ)) for ч in re.findall(r'[٠-٩]+', м.group(0))[1:])
    return []


def собрать(н, х_все, фатх, умда, раджаб, джами, миркат):
    д, гл, х, дт = х_все[str(н)]
    русский = re.sub(r'<[^>]+>', '', ' '.join(х.get('ru', [])))
    чист = lambda т: re.sub(r'<[^>]+>', '', т)
    о = [f'# Досье: хадис {н}. {х.get("t", "")}', '',
         f'Книга: {д["ru"]}', f'Глава аль-Бухари: {гл.get("ru") or "без названия"} — {гл.get("ar", "")}']
    if гл.get('intro'):
        о += ['Вступление главы: ' + ' '.join(чист(п) for п in гл['intro'])]
    о += ['', '## Наш перевод', русский, '', '## Арабский', без_огласовок(чист(х['x']))]
    if х.get('z'):
        о += ['Замечание после хадиса: ' + без_огласовок(чист(х['z']))]
    пов = повторы(фатх, н)
    похожие = [] if пов else sorted({int(р) for р in дт.get('r', []) if р.isdigit()} - {н})  # строки в «Фатхе» бывает нет
    о += ['', '## Где', 'Повторы у аль-Бухари по строке «Фатха»: ' + (', '.join(map(str, пов)) or 'строки нет'),
          *(['Строки повторов в «Фатхе» нет. Карта hadith.dev даёт ' + ', '.join(map(str, похожие)) +
             ': это могут быть и другие хадисы на ту же тему, сверь по «Фатху».'] if похожие else []),
          'Другие сборники: ' + ('; '.join(f'{имя} ({ч})' for _, имя, ч in дт.get('o', [])[:10]) or 'нет')]

    нач, кон = фатх.место(н)
    # Ибн Хаджар нередко приводит несколько хадисов подряд, а разбирает после: тогда берём страницы до конца их разбора
    к, подряд = н, []
    while (к := фатх.подряд(к)) and len(подряд) < 8:
        подряд.append(к)
        кон = max(кон, фатх.место(к)[1])
    о.append('\n## Фатх аль-Бари, Ибн Хаджар')
    if подряд:
        о.append(f'Ибн Хаджар приводит подряд и хадисы {", ".join(map(str, подряд))}, а разбирает их после: страницы идут до '
                 'конца этого разбора, бери только своё.')
    о += [блок('Фатх', с) for с in фатх.стр[max(нач - 1, 0):кон + 1] if с['t']]
    уже = set(range(нач - 1, кон + 1))
    for р in пов or похожие:
        м = фатх.место(р)
        if not м:
            continue
        стр = [и for и in range(м[0], min(м[1], м[0] + ДО_СТРАНИЦ_НА_ПОВТОР - 1) + 1) if и not in уже]
        if стр:
            о.append(f'\n### Фатх, место повтора {р}')
            о += [блок('Фатх', фатх.стр[и]) for и in стр]
            уже.update(стр)

    м = умда.место(н)
    if м:
        о.append('\n## Умдат аль-Кари, аль-Айни (без рубрик о грамматике, огласовке имён и тонкостях цепи)')
        for с in умда.стр[м[0]:м[1] + 1]:
            о.append(f'\n[Умда {с["v"]}/{с["p"]}, id {с["id"]}]\n{срезать_умду(без_огласовок(с["t"]))}\n')

    о.append('\n## Фатх аль-Бари, Ибн Раджаб')
    м = раджаб.место(н)
    if м and any(ном == н for ном, _ in раджаб.номера):
        о += [блок('Раджаб', с, True) for с in раджаб.стр[м[0]:м[1] + 1]]
    elif н > 58:  # Книги знания и омовения в этом издании Ибн Раджаба нет
        о.append('В этом издании разбора нет.')
    else:
        стр = найти_фразой(раджаб, чист(х['x']), нужно=2, страниц=8, до=ГРАНИЦА_РАДЖАБА)
        о += ['Номера на странице нет, найдено по фразе, начало может быть раньше.'] if стр else []
        о += [блок('Раджаб', с, True) for с in стр] if стр else ['В издании не найдено: у Ибн Раджаба здесь пропуск.']

    if н in ДЖАМИ_НОМЕРА:
        м = джами.место(ДЖАМИ_НОМЕРА[н])
        о.append(f'\n## Джами аль-улюм, Ибн Раджаб (хадис {ДЖАМИ_НОМЕРА[н]})')
        о += [блок('Джами', с, True) for с in джами.стр[м[0]:м[1] + 1]]

    стр = найти_фразой(миркат, чист(х['x']))
    о.append('\n## Миркат, Али аль-Кари (найдено по фразе, это может быть и другое место)')
    о += [блок('Миркат', с) for с in стр] if стр else ['Не найдено по фразе.']
    os.makedirs(ДОСЬЕ, exist_ok=True)
    текст = '\n'.join(о) + '\n'
    open(f'{ДОСЬЕ}/{н}.md', 'w', encoding='utf-8').write(текст)
    return len(текст)


номера = []
for а in sys.argv[1:]:
    от, _, до = а.partition('-')
    номера += range(int(от), int(до or от) + 1)
кн = {б: Книга(б, {УМДА: НАЧАЛА_УМДЫ, РАДЖАБ: НАЧАЛА_РАДЖАБА}.get(б)) for б in (ФАТХ, УМДА, РАДЖАБ, ДЖАМИ, МИРКАТ)}
все = хадисы()
дополнить_начала(кн[УМДА], все)
дополнить_начала(кн[РАДЖАБ], все)
for н in номера:
    if str(н) not in все:  # слит с соседним или вне переведённых книг
        continue
    print(н, собрать(н, все, кн[ФАТХ], кн[УМДА], кн[РАДЖАБ], кн[ДЖАМИ], кн[МИРКАТ]) // 1000, 'тыс. знаков', flush=True)
