"""Проверка файла перевода против книги: python3 перевод/проверить.py 3
Сборка сводит главы по порядку, поэтому лишняя или пропущенная глава незаметно сдвинет заглавия всей книги.
Смотрит: те же главы и те же номера хадисов, текст у каждого хадиса, заголовки, ﷺ, сноски, запретные слова.
"""
import json, os, re, sys

ЗДЕСЬ = os.path.dirname(os.path.abspath(__file__))
ЗАПРЕТ = ['удовлетворил', 'насытил', 'утолил']

н = int(sys.argv[1])
кн = json.load(open(f'{ЗДЕСЬ}/../data/bukhari/{н:02}.json', encoding='utf-8'))
строки = open(f'{ЗДЕСЬ}/бухари/{н:02}.md', encoding='utf-8').read().split('\n## Вопросы')[0].split('\n')
ошибки, главы, х = [], [], None
for с in строки:
    if с.startswith('## '):
        главы.append([])
        х = None
    elif с.startswith('### '):
        номер, _, загл = с[4:].partition('|')
        х = {'n': номер.strip(), 't': загл.strip(), 'текст': []}
        if not главы:
            ошибки.append(f'хадис {х["n"]} раньше первой главы')
            главы.append([])
        главы[-1].append(х)
        if not х['t']:
            ошибки.append(f'нет заголовка у {х["n"]}')
        elif len(х['t'].split()) > 9:
            ошибки.append(f'длинный заголовок у {х["n"]}: {х["t"]}')
    elif х and с.strip():
        х['текст'].append(с)

if len(главы) != len(кн['ch']):
    ошибки.append(f'глав {len(главы)}, в книге {len(кн["ch"])}')
for и, (г, ар) in enumerate(zip(главы, кн['ch'])):
    нужно = [h['n'] for h in ар['h']]
    есть = [х['n'] for х in г]
    if нужно != есть:
        ошибки.append(f'глава {и + 1} ({ар["ar"][:40]}): нужно {нужно}, есть {есть}')
весь = '\n'.join(строки)
for г in главы:
    for х in г:
        if not х['текст']:
            ошибки.append(f'нет текста у {х["n"]}')
if re.search(r'[؀-ۿ]', весь):
    ошибки.append('арабские буквы в переводе')
for м in re.finditer(r'Пророк(?:а|у|ом|е)?(?![а-я])(?! ﷺ| Аллаха ﷺ)', весь):  # «Пророк Аллаха ﷺ» — نبي الله
    ошибки.append('нет ﷺ: ' + весь[max(0, м.start() - 25):м.end() + 15].replace('\n', ' '))
for с in ЗАПРЕТ:
    if с in весь.lower():
        ошибки.append(f'запретное слово: {с}')
ссылки, сноски = set(re.findall(r'\[\^(\w+)\](?!:)', весь)), set(re.findall(r'\[\^(\w+)\]:', весь))
if ссылки != сноски:
    ошибки.append(f'сноски не сходятся: {sorted(ссылки ^ сноски)}')
for о in ошибки:
    print('ошибка:', о)
print(f'глав {len(главы)}, хадисов {sum(map(len, главы))}, ошибок {len(ошибки)}')
sys.exit(1 if ошибки else 0)
